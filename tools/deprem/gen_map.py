#!/usr/bin/env python3
"""Generates apps/deprem/map_data.c: Turkey and its neighbours, clipped and simplified, for the Son Depremler map.

Source: Natural Earth 1:50m admin-0 countries and lakes (public domain, https://www.naturalearthdata.com/).

  gen_map.py <ne_50m_admin_0_countries.geojson> <ne_50m_lakes.geojson> > apps/deprem/map_data.c

The GeoJSON files are in nvkelso/natural-earth-vector (geojson/). Rings are clipped to CLIP (Sutherland-Hodgman),
simplified with Douglas-Peucker (TOL degrees) and stored as int16 hundredths of a degree.
"""
import json, sys

CLIP = (22.5, 33.5, 46.5, 44.5)  # lon_min, lat_min, lon_max, lat_max
TOL = 0.03
MIN_AREA = 0.004  # square degrees: drops tiny islets that would be a pixel


def clip(ring, edge):
    """Sutherland-Hodgman against one half-plane; edge = (axis, value, keep_greater)."""
    axis, v, ge = edge
    inside = (lambda p: p[axis] >= v) if ge else (lambda p: p[axis] <= v)
    out = []
    for i in range(len(ring)):
        a, b = ring[i - 1], ring[i]
        ia, ib = inside(a), inside(b)
        if ia != ib:
            t = (v - a[axis]) / (b[axis] - a[axis])
            out.append((a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])))
        if ib:
            out.append(b)
    return out


def clip_rect(ring):
    x0, y0, x1, y1 = CLIP
    for e in ((0, x0, True), (0, x1, False), (1, y0, True), (1, y1, False)):
        if not ring:
            break
        ring = clip(ring, e)
    return ring


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    (ax, ay), (bx, by) = pts[0], pts[-1]
    dx, dy = bx - ax, by - ay
    n = (dx * dx + dy * dy) ** 0.5
    best, bi = -1.0, 0
    for i in range(1, len(pts) - 1):
        px, py = pts[i]
        d = abs(dy * (px - ax) - dx * (py - ay)) / n if n else ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
        if d > best:
            best, bi = d, i
    if best <= tol:
        return [pts[0], pts[-1]]
    return dp(pts[: bi + 1], tol)[:-1] + dp(pts[bi:], tol)


def simplify(ring):
    # split the closed ring at its two farthest-apart points so DP has distinct ends
    far = max(range(len(ring)), key=lambda i: (ring[i][0] - ring[0][0]) ** 2 + (ring[i][1] - ring[0][1]) ** 2)
    a = dp(ring[: far + 1], TOL)
    b = dp(ring[far:] + [ring[0]], TOL)
    return a[:-1] + b[:-1]


def area(r):
    return abs(sum(r[i - 1][0] * r[i][1] - r[i][0] * r[i - 1][1] for i in range(len(r)))) / 2


def rings_of(feature):
    g = feature["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    for poly in polys:
        yield [tuple(p[:2]) for p in poly[0]]  # outer ring only (no country here has holes worth drawing)


def main():
    countries, lakes = (json.load(open(p, encoding="utf-8")) for p in sys.argv[1:3])
    out = []  # (kind, points): kind 1 = Turkey, 0 = other land, 2 = lake
    for f in countries["features"]:
        kind = 1 if f["properties"]["ADM0_A3"] == "TUR" else 0
        for r in rings_of(f):
            out.append((kind, r))
    for f in lakes["features"]:
        for r in rings_of(f):
            out.append((2, r))
    rings = []
    for kind, r in out:
        if r[0] == r[-1]:
            r = r[:-1]
        r = clip_rect(r)
        if len(r) < 3 or area(r) < MIN_AREA:
            continue
        r = simplify(r)
        q = []
        for x, y in r:
            p = (round(x * 100), round(y * 100))
            if not q or q[-1] != p:
                q.append(p)
        if len(q) >= 3 and area(q) >= MIN_AREA * 1e4:
            rings.append((kind, q))
    rings.sort(key=lambda kr: (kr[0] == 2, kr[0] == 1))  # land, then Turkey, then lakes on top
    pts, starts = [], []
    for kind, q in rings:
        starts.append((len(pts), len(q), kind))
        pts += q
    w = sys.stdout.write
    w("/* Generated by tools/deprem/gen_map.py from Natural Earth 1:50m admin-0 countries and lakes (public domain).\n")
    w(" * Do not edit. Points are hundredths of a degree (lon, lat). */\n")
    w('#include "deprem.h"\n\n')
    w("const short dq_map_pts[][2] = {\n")
    for i in range(0, len(pts), 8):
        w("\t" + " ".join("{ %d, %d }," % p for p in pts[i : i + 8]) + "\n")
    w("};\n\n")
    w("const DqRing dq_map_rings[] = {\n")
    for s, n, k in starts:
        w("\t{ %d, %d, %d },\n" % (s, n, k))
    w("};\n\n")
    w("const int dq_map_n_rings = %d;\n" % len(starts))
    sys.stderr.write("%d rings, %d points\n" % (len(starts), len(pts)))


main()
