#!/usr/bin/env python3
"""Generates apps/deprem/places_data.c: Kandilli writes place names in ASCII capitals ("SINDIRGI (BALIKESIR)");
this table gives the Turkish spelling of every province and district name, plus common geographic words, so the
app can show "Sındırgı (Balıkesir)".

  gen_places.py <il-ilce.json> > apps/deprem/places_data.c

il-ilce.json: the province/district list from snrylmz/il-ilce-json (js/il-ilce.json) — {"data": [{"il_adi",
"ilceler": [{"ilce_adi"}]}]}. Names that fold to the same ASCII key with different spellings are left out.
"""
import json, sys

FOLD = str.maketrans("ÇĞİÖŞÜÂÎÛ", "CGIOSUAIU")
EXTRA = [  # words that occur in Kandilli place names
    "Akdeniz", "Karadeniz", "Ege", "Marmara", "Denizi", "Körfezi", "Açıkları", "Adası", "Adaları", "Gölü", "Barajı",
    "Boğazı", "Yunanistan", "Bulgaristan", "Gürcistan", "Ermenistan", "Azerbaycan", "İran", "Irak", "Suriye",
    "Kıbrıs", "Lübnan", "Girit", "Midilli", "Sakız", "Sisam", "İstanköy", "Rodos", "Limni", "Gökçeada", "Bozcaada",
    "Kuzey", "Güney", "Doğu", "Batı", "Sınır", "Bölgesi", "Oniki", "Kerpe", "Kaşot", "Taşoz", "Semadirek", "Sakarya",
]


def tr_title(word):
    w = word.replace("I", "ı").replace("İ", "i").lower()
    return w[0].replace("i", "İ").replace("ı", "I").upper() + w[1:] if w else w


def main():
    data = json.load(open(sys.argv[1], encoding="utf-8"))["data"]
    names = set(EXTRA)
    for il in data:
        names.add(il["il_adi"].strip())
        for d in il["ilceler"]:
            for part in d["ilce_adi"].strip().split():
                names.add(tr_title(part))
    by_key = {}
    for n in names:
        if n == "Merkez":
            continue
        k = tr_upper(n).translate(FOLD)
        assert k.isascii(), n
        by_key.setdefault(k, set()).add(n)
    rows = sorted((k, next(iter(v))) for k, v in by_key.items() if len(v) == 1)
    # keep only names that differ from plain ASCII title case (others need no table entry)
    rows = [(k, n) for k, n in rows if n != ascii_title(k)]
    w = sys.stdout.write
    w("/* Generated by tools/deprem/gen_places.py from the Turkish province/district list. Do not edit.\n")
    w(" * ASCII capitals (as Kandilli writes them) → Turkish spelling, sorted by key for bsearch. */\n")
    w('#include "deprem.h"\n\n')
    w("const DqPlaceName dq_place_names[] = {\n")
    for k, n in rows:
        w('\t{ "%s", "%s" },\n' % (k, n))
    w("};\n\n")
    w("const int dq_n_place_names = %d;\n" % len(rows))
    sys.stderr.write("%d names\n" % len(rows))


def tr_upper(s):
    return s.replace("i", "İ").replace("ı", "I").upper()


def ascii_title(k):
    return k[0] + k[1:].lower()


main()
