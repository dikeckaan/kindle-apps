/* Son Depremler: Kandilli (KRDAE) and EMSC earthquake lists, filters, distances and the map projection. */
#ifndef DEPREM_H
#define DEPREM_H

#define DQ_MAX 500
#define DQ_TR_OFFSET (3 * 3600) /* Türkiye time: UTC+3 all year */

typedef enum { DQ_SRC_NONE, DQ_SRC_KANDILLI, DQ_SRC_EMSC } DqSource;

typedef struct {
	long t;               /* unix time (UTC) */
	double lat, lon, depth, mag;
	char mtype[4];        /* "ML", "Mw", "MD", "M" */
	char place[96];       /* UTF-8, Turkish spelling where known */
} Quake;

/* windows-1254 (Kandilli's page) → UTF-8; returns the output length (always NUL-terminated, never splits a character) */
int dq_cp1254_to_utf8(const char *in, int len, char *out, int cap);

/* Parses the raw Kandilli lst0.asp page (windows-1254) into out[] newest first; returns the count (0 = unusable). */
int dq_parse_kandilli(const char *body, int len, Quake *out, int max);
/* Parses an EMSC FDSN event JSON (format=json) into out[] newest first; returns the count (0 = unusable). */
int dq_parse_emsc(const char *body, int len, Quake *out, int max);
/* Either of the above, by the body's format; *src says which. */
int dq_parse(const char *body, int len, Quake *out, int max, DqSource *src);

/* "YESILDERE-SIMAV (KUTAHYA)" → "Yesildere-Simav (Kütahya)": title case, Turkish spelling of known names */
void dq_place_pretty(const char *ascii_caps, char *out, int cap);
/* EMSC Flynn region ("WESTERN TURKEY") → Turkish ("Batı Türkiye"), else title case */
void dq_region_pretty(const char *region, char *out, int cap);

/* indexes of quakes with mag >= min_mag and t >= since, in list order; returns the count */
int dq_filter(const Quake *q, int n, double min_mag, long since, int *idx, int max);
/* idx[] reordered by magnitude, largest first (ties: newer first) */
void dq_sort_by_mag(const Quake *q, int *idx, int n);

double dq_distance_km(double lat1, double lon1, double lat2, double lon2); /* great circle (haversine) */
int dq_radius(double mag, int scale_px); /* map circle radius in px for a magnitude (scale_px: radius of an M3) */

/* "az önce", "12 dk önce", "3 sa önce", "2 gün önce" (translated) */
void dq_ago(long now, long t, char *out, int cap);

/* ---- map: equirectangular projection fitted to a pixel rectangle ---- */
typedef struct { double lon0, lat1, scale, kx; int x, y, w, h; } DqProj;
#define DQ_MAP_LON0 23.6
#define DQ_MAP_LON1 45.4
#define DQ_MAP_LAT0 34.6
#define DQ_MAP_LAT1 43.0
/* fits [lon0,lon1]×[lat0,lat1] into the rectangle x,y,w,h (aspect kept, centred); x scaled by cos(mid latitude) */
void dq_proj_fit(DqProj *p, int x, int y, int w, int h, double lon0, double lon1, double lat0, double lat1);
void dq_project(const DqProj *p, double lat, double lon, int *px, int *py);
int  dq_proj_height(int w, double lon0, double lon1, double lat0, double lat1); /* rectangle height for width w */
void dq_unproject(const DqProj *p, int px, int py, double *lat, double *lon); /* pixel → coordinates */

/* ---- map view: a zoom (1×, 2×, 4×) and the centre of what is shown, always inside the full map ---- */
#define DQ_ZOOM_MAX 4
typedef struct { int zoom; double lat, lon; } DqView;
void dq_view_reset(DqView *v); /* 1×: the whole map */
void dq_view_clamp(DqView *v); /* zoom into 1..DQ_ZOOM_MAX (a power of two), the centre so the view stays on the map */
int  dq_view_zoom(DqView *v, int dir); /* dir > 0 doubles, < 0 halves the zoom (centre kept); 1 if anything changed */
int  dq_view_pan(DqView *v, double fx, double fy); /* by fractions of the shown width/height (+x east, +y south); 1 if moved */
/* the view's projection: `full` (dq_proj_fit of the whole map) magnified around the centre, same pixel rectangle */
void dq_proj_view(DqProj *p, const DqProj *full, const DqView *v);

/* city labels for the map; zoom: the smallest zoom they are shown at (more cities as the map is magnified) */
typedef struct { const char *name; double lat, lon; int zoom; } DqCity;
extern const DqCity dq_cities[];
extern const int dq_n_cities;

/* map outline data (map_data.c, generated by tools/deprem/gen_map.py) */
typedef struct { int start, n, kind; } DqRing; /* kind: 0 land, 1 Turkey, 2 lake */
extern const short dq_map_pts[][2];            /* hundredths of a degree: { lon, lat } */
extern const DqRing dq_map_rings[];
extern const int dq_map_n_rings;
int dq_ring_contains(const DqRing *r, double lat, double lon); /* even-odd point in polygon */
/* x crossings of the projected ring with the pixel row y (centre of the row), sorted; returns the count */
int dq_ring_scan(const DqProj *p, const DqRing *r, int y, int *xs, int max);

/* place names (places_data.c, generated by tools/deprem/gen_places.py) */
typedef struct { const char *key, *name; } DqPlaceName;
extern const DqPlaceName dq_place_names[];
extern const int dq_n_place_names;
#endif
